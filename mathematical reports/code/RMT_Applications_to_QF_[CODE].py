def monte_carlo_silverstein(N, T, trials=100):
    """
    Runs multiple trials to prove the Baik & Silverstein limit
    is the exact expected value (center) of the sample spikes.
    """
    q = N / T

    # True Covariance (Strict Spiked Model)
    C = np.full((N, N), 0.30)
    np.fill_diagonal(C, np.random.uniform(0.5, 2.5, size=N))

    ev_C = np.linalg.eigvalsh(C)
    max_true_alpha = ev_C.max()

    # Calculate the theoretical B&S Limit
    bs_prediction = max_true_alpha + (q * max_true_alpha) / (max_true_alpha - 1)

    observed_spikes = []

    print(f"Running {trials} trials for N={N}, T={T} (q={q:.2f})...")
    for i in range(trials):
        # Generate new random sample
        L_chol = np.linalg.cholesky(C)
        Z = np.random.normal(0, 1, size=(N, T))
        Y = L_chol @ Z

        # SCM and top eigenvalue
        S_1 = (Y @ Y.T) / T
        observed_spikes.append(np.linalg.eigvalsh(S_1).max())

    observed_spikes = np.array(observed_spikes)
    mean_observed = observed_spikes.mean()

    print(f"--> B&S Theoretical Limit : {bs_prediction:.2f}")
    print(f"--> Avg Observed Spike    : {mean_observed:.2f}")
    print(f"--> Monte Carlo Error     : {abs(bs_prediction - mean_observed):.4f}\n")

    return observed_spikes, bs_prediction

