def ledoit_wolf_constant_correlation(Y, S):
    N, T_loc = Y.shape
    s_diag  = np.diag(S)
    sqrt_s  = np.sqrt(s_diag)

    # average off-diagonal sample correlation
    corr = S / np.outer(sqrt_s, sqrt_s)
    r_bar = corr[np.triu_indices(N, k=1)].mean()

    # constant-correlation target
    F = r_bar * np.outer(sqrt_s, sqrt_s)
    np.fill_diagonal(F, s_diag)

    # pi_ij = (1/T) sum_t (y_it y_jt - s_ij)^2 = (1/T) sum_t y_it^2 y_jt^2 - s_ij^2
    Y2 = Y * Y
    Pi = (Y2 @ Y2.T) / T_loc - S * S
    pi_hat = Pi.sum()

    # theta_{ii, ij} = (1/T) sum_t y_it^3 y_jt - s_ii s_ij
    Y3 = Y2 * Y
    Theta = (Y3 @ Y.T) / T_loc - np.outer(s_diag, np.ones(N)) * S

    # rho_hat = sum_i pi_ii + (r_bar/2) sum_{i!=j} [sqrt(s_jj/s_ii) Theta_ij + sqrt(s_ii/s_jj) Theta_ji]
    rho_diag = np.trace(Pi)
    ratio = np.outer(1.0 / sqrt_s, sqrt_s)  # ratio[i,j] = sqrt(s_jj/s_ii)
    off_mask = 1.0 - np.eye(N)
    rho_off = (r_bar / 2.0) * ((ratio * Theta + ratio.T * Theta.T) * off_mask).sum()
    rho_hat = rho_diag + rho_off

    # gamma_hat = ||F - S||_F^2
    gamma_hat = ((F - S) ** 2).sum()

    # kappa and clipped alpha
    kappa = (pi_hat - rho_hat) / gamma_hat
    alpha = float(np.clip(kappa / T_loc, 0.0, 1.0))

    return alpha * F + (1.0 - alpha) * S, alpha, F

