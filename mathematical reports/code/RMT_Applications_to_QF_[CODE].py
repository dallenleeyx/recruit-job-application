def debiased_rie_cleaning(evalues, N, q):
    """
    Implements the debiased Rotationally Invariant Estimator (RIE)
    from Bun, Bouchaud, and Potters (2016) - Box 1.
    """
    # Initialize array for the cleaned eigenvalues
    xi_hat = np.zeros_like(evalues, dtype=float)

    # Identify the smallest empirical eigenvalue (lambda_N in the paper)
    lambda_min = np.min(evalues)

    # calc spectral bounds
    sigma_sq = lambda_min / (1 - np.sqrt(q))**2
    lambda_plus = lambda_min * ((1 + np.sqrt(q)) / (1 - np.sqrt(q)))**2

    for k, lambda_k in enumerate(evalues):
        # Define the complex variable z_k
        z_k = lambda_k - (1j / np.sqrt(N))

        mask = np.arange(N) != k
        lambda_j = evalues[mask]

        # Calculate the Stieltjes transform approximation s_k(z_k)
        s_k = (1 / N) * np.sum(1 / (z_k - lambda_j))

        # Calculate xi_k^{RIE}
        denominator_1 = np.abs(1 - q + q * z_k * s_k)**2
        xi_k_rie = lambda_k / denominator_1

        # Calculate the Marcenko-Pastur Stieltjes transform g_mp(z_k)
        sqrt_term = np.sqrt(z_k - lambda_min) * np.sqrt(z_k - lambda_plus)
        g_mp = (z_k + sigma_sq * (q - 1) - sqrt_term) / (2 * q * z_k * sigma_sq)

        # Calculate Gamma_k
        Gamma_k = sigma_sq * (np.abs(1 - q + q * z_k * g_mp)**2) / lambda_k

        if Gamma_k > 1:
            xi_hat[k] = Gamma_k * xi_k_rie
        else:
            xi_hat[k] = xi_k_rie

    return xi_hat


