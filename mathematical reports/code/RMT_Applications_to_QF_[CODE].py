# --- Helper Function for Median Matching ---
def get_mp_median(q_val):
    """
    Numerically calculates the theoretical median of the standard Marchenko-Pastur
    distribution (where sigma^2 = 1) for a given q = N/T.
    """
    lam_min = (1 - np.sqrt(q_val))**2
    lam_max = (1 + np.sqrt(q_val))**2

    def mp_pdf(x):
        # The probability density function of the Marchenko-Pastur law
        if x <= lam_min or x >= lam_max:
            return 0.0
        return np.sqrt((lam_max - x) * (x - lam_min)) / (2 * np.pi * q_val * x)

    def target_func(limit):
        # We want to find the limit where the integral (CDF) equals 0.5
        val, _ = integrate.quad(mp_pdf, lam_min, limit)
        return val - 0.5

    # Find the root (the theoretical median) between the min and max bounds
    res = optimize.root_scalar(target_func, bracket=[lam_min + 1e-8, lam_max - 1e-8], method='brentq')
    return res.root


