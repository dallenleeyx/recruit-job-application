# ## 2. Covariance cleaning estimators
#
# Cleaning is done on the CORRELATION matrix (standard RMT practice --
# Marchenko-Pastur theory applies to unit-variance inputs), rescaled back to
# a covariance matrix with the sample standard deviations. This separates
# volatility estimation (easy) from correlation structure estimation (hard,
# and where RMT actually helps).
#
# Flat baselines:
#   S1 - sample covariance (no cleaning)
#   S2 - Ledoit-Wolf linear shrinkage (toward scaled identity)
#   S3 - Marchenko-Pastur eigenvalue clipping (RMT hard-threshold)

# %%
def to_correlation(cov):
    std = np.sqrt(np.diag(cov))
    std_safe = np.where(std < 1e-12, 1e-12, std)
    corr = cov / np.outer(std_safe, std_safe)
    np.fill_diagonal(corr, 1.0)
    return corr, std


def to_covariance(corr, std):
    return corr * np.outer(std, std)


def sample_cov(returns):
    return np.cov(returns, rowvar=False)


def ledoit_wolf_cov(returns):
    return LedoitWolf().fit(returns).covariance_


def mp_edge(q, sigma2=1.0):
    """Marchenko-Pastur upper edge for aspect ratio q = N/T."""
    return sigma2 * (1.0 + np.sqrt(q)) ** 2


def clip_correlation(corr, q):
    """Hard-threshold eigenvalue cleaning (Bouchaud-Potters style): keep
    eigenvalues above the MP edge as signal, replace everything below with
    their common average (pure noise), preserving the trace."""
    n = corr.shape[0]
    eigvals, eigvecs = np.linalg.eigh(corr)
    lam_plus = mp_edge(q)

    signal_mask = eigvals > lam_plus
    n_noise = (~signal_mask).sum()

    cleaned = eigvals.copy()
    if n_noise > 0:
        noise_avg = (n - eigvals[signal_mask].sum()) / n_noise
        cleaned[~signal_mask] = max(noise_avg, 1e-8)

    C_clean = eigvecs @ np.diag(cleaned) @ eigvecs.T
    C_clean = (C_clean + C_clean.T) / 2
    np.fill_diagonal(C_clean, 1.0)
    return C_clean, eigvals, lam_plus


def eigenvalue_clip_cov(returns):
    T, N = returns.shape
    cov = sample_cov(returns)
    corr, std = to_correlation(cov)
    q = N / T
    corr_clean, _, _ = clip_correlation(corr, q)
    return to_covariance(corr_clean, std)


# --- cross-sector (rectangular) cleaning ---
# Practical implementation grounded in RMT edge theory: debiased hard-
# thresholding of the singular-value spectrum of a rectangular cross-
# correlation block, using the known noise edge for singular values of a
# cross-covariance between two independent Gaussian blocks of aspect ratios
# q1=n1/T, q2=n2/T. This is NOT a literal reproduction of the full optimal
# nonlinear formula in Benaych-Georges, Bouchaud & Potters (2023, Ann. Appl.
# Probab.) -- that requires numerically solving fixed-point equations of the
# rectangular free convolution. This is the accessible, still RMT-principled
# version: under the null of no true cross-sector correlation, singular
# values of the empirical cross-correlation block concentrate below a known
# edge; only what's above is treated as signal, debiased in quadrature for
# expected noise inflation.

def cross_block_edge(q1, q2):
    return np.sqrt(q1) + np.sqrt(q2)


def clean_cross_block(C_ij, T):
    n_i, n_j = C_ij.shape
    q1, q2 = n_i / T, n_j / T
    edge = cross_block_edge(q1, q2)
    U, s, Vt = np.linalg.svd(C_ij, full_matrices=False)
    s_clean = np.sqrt(np.clip(s ** 2 - edge ** 2, 0, None))
    return (U * s_clean) @ Vt


def psd_repair(corr, eps_rel=1e-3):
    """Project onto the PSD cone, then renormalize to a valid correlation
    matrix. eps_rel floors the smallest eigenvalue as a FRACTION of the
    largest one -- an absolute floor is wrong here: block-wise cleaning +
    reassembly can leave small negative eigenvalues sitting next to a large
    top eigenvalue (e.g. ~100-200, driven by a genuine market factor), and
    clipping to a tiny absolute constant creates an artificially near-
    singular matrix, which blows up GMV weights."""
    corr = (corr + corr.T) / 2
    eigvals, eigvecs = np.linalg.eigh(corr)
    eps_abs = eps_rel * eigvals[-1]
    eigvals_clipped = np.clip(eigvals, eps_abs, None)
    repaired = eigvecs @ np.diag(eigvals_clipped) @ eigvecs.T
    d = np.sqrt(np.diag(repaired))
    repaired = repaired / np.outer(d, d)
    np.fill_diagonal(repaired, 1.0)
    return repaired


# ## 3. Sector-hierarchical cleaning + hierarchical GMV hedge

# %%
def build_sector_index(sector_series, asset_order):
    sector_series = sector_series.reindex(asset_order)
    groups = {}
    for sector in sector_series.unique():
        idx = np.where(sector_series.values == sector)[0]
        groups[sector] = idx
    return groups


def sector_hierarchical_cov(returns, sector_groups, min_sector_size=5):
    T, N = returns.shape
    cov_sample = np.cov(returns, rowvar=False)
    corr_sample, std = to_correlation(cov_sample)

    corr_clean = np.zeros_like(corr_sample)
    diagnostics = {"sectors": {}, "cross_pairs": {}}
    sector_names = list(sector_groups.keys())

    # 1. clean each diagonal (intra-sector) block
    for name, idx in sector_groups.items():
        n_k = len(idx)
        block = corr_sample[np.ix_(idx, idx)]
        if n_k < min_sector_size:
            cleaned_block = block
            eigvals, lam_plus = np.linalg.eigvalsh(block), np.nan
        else:
            q_k = n_k / T
            cleaned_block, eigvals, lam_plus = clip_correlation(block, q_k)
        corr_clean[np.ix_(idx, idx)] = cleaned_block
        diagnostics["sectors"][name] = {"n": n_k, "eigvals": eigvals, "mp_edge": lam_plus}

    # 2. clean each off-diagonal (cross-sector) block
    for i, name_i in enumerate(sector_names):
        idx_i = sector_groups[name_i]
        for name_j in sector_names[i + 1:]:
            idx_j = sector_groups[name_j]
            block_ij = corr_sample[np.ix_(idx_i, idx_j)]
            if len(idx_i) < min_sector_size or len(idx_j) < min_sector_size:
                cleaned_ij = block_ij
            else:
                cleaned_ij = clean_cross_block(block_ij, T)
            corr_clean[np.ix_(idx_i, idx_j)] = cleaned_ij
            corr_clean[np.ix_(idx_j, idx_i)] = cleaned_ij.T
            diagnostics["cross_pairs"][(name_i, name_j)] = {
                "raw_frobenius": np.linalg.norm(block_ij),
                "clean_frobenius": np.linalg.norm(cleaned_ij),
            }

    np.fill_diagonal(corr_clean, 1.0)
    corr_repaired = psd_repair(corr_clean)
    cov_clean = to_covariance(corr_repaired, std)

    diagnostics["corr_sample"] = corr_sample
    diagnostics["corr_clean_prerepair"] = corr_clean
    diagnostics["corr_clean"] = corr_repaired
    return cov_clean, diagnostics


def gmv_weights(cov, ridge=1e-10):
    """Unconstrained (allows shorting) global-minimum-variance weights."""
    n = cov.shape[0]
    cov_reg = cov + ridge * np.eye(n) * np.trace(cov) / n
    ones = np.ones(n)
    inv_cov_ones = np.linalg.solve(cov_reg, ones)
    return inv_cov_ones / (ones @ inv_cov_ones)


def hierarchical_hedge_weights(cov_clean, sector_groups):
    """Two-level hierarchical GMV: (1) GMV within each sector, (2) project
    cov_clean onto the resulting sector sub-portfolios (guaranteed PSD, it's
    a quadratic form), (3) GMV across sectors, (4) combine to asset weights."""
    N = cov_clean.shape[0]
    sector_names = list(sector_groups.keys())
    K = len(sector_names)

    W = np.zeros((N, K))
    for k, name in enumerate(sector_names):
        idx = sector_groups[name]
        block = cov_clean[np.ix_(idx, idx)]
        W[idx, k] = gmv_weights(block)

    sigma_sector = W.T @ cov_clean @ W
    sector_alloc = gmv_weights(sigma_sector)
    final_weights = W @ sector_alloc
    return final_weights, sector_alloc, sigma_sector, W



# ## 4. Rolling-window backtest

# %%
def run_backtest(returns_df, sector_groups, lookback=504, holding_period=21,
                  min_start=None, verbose=True):
    dates = returns_df.index
    T_total, N = returns_df.shape
    values = returns_df.values

    methods = ["S1_sample", "S2_ledoit_wolf", "S3_mp_clip", "Sector_full", "Sector_hedge"]
    daily_returns = {m: pd.Series(index=dates, dtype=float) for m in methods}
    diagnostics = []

    start_idx = lookback
    if min_start is not None:
        start_idx = max(start_idx, dates.searchsorted(min_start))

    rebalance_points = list(range(start_idx, T_total - 1, holding_period))

    for r_i, t in enumerate(rebalance_points):
        train = values[t - lookback: t]
        hold_end = min(t + holding_period, T_total)
        test = values[t: hold_end]
        if test.shape[0] == 0:
            continue

        cov_s1 = sample_cov(train)
        cov_s2 = ledoit_wolf_cov(train)
        cov_s3 = eigenvalue_clip_cov(train)
        cov_sector, diag = sector_hierarchical_cov(train, sector_groups)

        w1 = gmv_weights(cov_s1)
        w2 = gmv_weights(cov_s2)
        w3 = gmv_weights(cov_s3)
        w4 = gmv_weights(cov_sector)
        w5, sector_alloc, sigma_sector, W = hierarchical_hedge_weights(cov_sector, sector_groups)

        weight_map = {"S1_sample": w1, "S2_ledoit_wolf": w2, "S3_mp_clip": w3,
                      "Sector_full": w4, "Sector_hedge": w5}

        test_dates = dates[t: hold_end]
        for m, w in weight_map.items():
            daily_returns[m].loc[test_dates] = test @ w

        if verbose and r_i % 6 == 0:
            print(f"  rebalance {r_i+1}/{len(rebalance_points)}  date={dates[t].date()}")

        diagnostics.append({"date": dates[t], "cov_sector_diag": diag, "sector_alloc": sector_alloc})

    result_df = pd.DataFrame(daily_returns).dropna(how="all")
    return result_df, diagnostics


def summarize_performance(result_df, period_name=""):
    ann_factor = np.sqrt(252)
    summary = pd.DataFrame({
        "ann_vol": result_df.std() * ann_factor,
        "ann_mean_return": result_df.mean() * 252,
        "n_days": result_df.count(),
    })
    summary["sharpe_like"] = summary["ann_mean_return"] / summary["ann_vol"]
    summary.index.name = f"method ({period_name})" if period_name else "method"
    return summary


