    ones = np.ones(len(inv_cov))

    # 3. Apply the GMV formula: w = (Sigma^-1 * 1) / (1^T * Sigma^-1 * 1)
    numerator = inv_cov @ ones
    denominator = ones.T @ inv_cov @ ones
    weights = numerator / denominator

    return weights


