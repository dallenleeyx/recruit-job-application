def get_gmv_weights(cov_matrix):

    # 1. Invert the covariance matrix
    inv_cov = np.linalg.pinv(cov_matrix)

    cond_no = np.linalg.cond(inv_cov)
    print(f"Condition Number: {cond_no}")

