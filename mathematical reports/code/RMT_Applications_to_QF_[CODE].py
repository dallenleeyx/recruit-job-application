def calculate_errors_for_params(N_val, T_val):
    # Using a deterministic seed for reproducibility of experiments, but varied by N, T
    local_rng_seed = N_val * 1000 + T_val
    np.random.seed(local_rng_seed)

    q_val = N_val / T_val

    # Generate a "true" matrix C
    C_local = np.full((N_val, N_val), 0.30)
    np.fill_diagonal(C_local, np.random.uniform(0.5, 2.5, size=N_val))

    # Generate data Y
    L_chol_local = np.linalg.cholesky(C_local)
    Z_local = np.random.normal(0, 1, size=(N_val, T_val))
    Y_local = L_chol_local @ Z_local

    # S_1: Sample Covariance Matrix
    S_1_local = (Y_local @ Y_local.T) / T_val

    # S_2: Linear shrinkage
    # ledoit_wolf_constant_correlation is defined globally in the previous cell
    S_2_local, _, _ = ledoit_wolf_constant_correlation(Y_local, S_1_local)

    # S_3: Eigenvalue clipping
    eigvals_S1_local, eigvecs_S1_local = np.linalg.eigh(S_1_local)
    sigma2_local = eigvals_S1_local.mean()
    lam_plus_clip_local = sigma2_local * (1.0 + np.sqrt(q_val)) ** 2
    is_bulk_local = eigvals_S1_local <= lam_plus_clip_local
    bulk_mean_local = eigvals_S1_local[is_bulk_local].mean()
    clipped_local = np.where(is_bulk_local, bulk_mean_local, eigvals_S1_local)
    S_3_local = eigvecs_S1_local @ np.diag(clipped_local) @ eigvecs_S1_local.T

    # S_4: Non-linear shrinkage
    xi_local = np.empty(N_val)
    eta_local = 1j * (N_val ** -0.5)

    for i, l_i in enumerate(eigvals_S1_local):
        others_local = np.delete(eigvals_S1_local, i)
        m_i_local = np.sum(1.0 / (l_i - others_local - eta_local))
        denom_local = 1.0 - q_val + (q_val * l_i / N_val) * m_i_local
        xi_local[i] = l_i / np.abs(denom_local) ** 2

    S_4_local = eigvecs_S1_local @ np.diag(xi_local) @ eigvecs_S1_local.T

    # frob_sq is defined globally in the previous cell
