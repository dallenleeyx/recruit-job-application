"""## Marchenko-Pastur Distribution

The Marchenko-Pastur distribution describes the limiting spectral distribution of large sample covariance matrices. For a random matrix $X$ of size $N \times P$ with independent and identically distributed entries with mean 0 and variance 1, the eigenvalues of the sample covariance matrix $W = \frac{1}{N} X^T X$ (which is $P \times P$) converge to the Marchenko-Pastur distribution as $N, P \to \infty$ with their ratio $q = P/N$ tending to a positive constant.

The probability density function (PDF) of the Marchenko-Pastur distribution for $\lambda \in [\lambda_{min}, \lambda_{max}]$ is given by:

$p(\lambda) = \frac{1}{2\pi q \sigma^2 \lambda} \sqrt{(\lambda_{max} - \lambda)(\lambda - \lambda_{min})}$

where:
- $\sigma^2$ is the variance of the entries of $X$ (here, $\sigma^2 = 1$ for standard normal).
- $q = P/N$
- $\lambda_{min} = \sigma^2 (1 - \sqrt{q})^2$
- $\lambda_{max} = \sigma^2 (1 + \sqrt{q})^2$
"""

# Parameters for Marchenko-Pastur distribution
q = P_features / N_samples # Ratio P/N

lambda_min = (1 - np.sqrt(q))**2
lambda_max = (1 + np.sqrt(q))**2

print(f"Ratio q (P/N): {q}")
print(f"Theoretical min eigenvalue (lambda_min): {lambda_min:.4f}")
print(f"Theoretical max eigenvalue (lambda_max): {lambda_max:.4f}")

# Define the Marchenko-Pastur PDF
def marchenko_pastur_pdf(lambda_val, q_ratio, sigma2, l_min, l_max):
    if l_min <= lambda_val <= l_max:
        return (1 / (2 * np.pi * q_ratio * sigma2 * lambda_val)) * \
               np.sqrt((l_max - lambda_val) * (lambda_val - l_min))
    else:
      return 0

# Vectorize the PDF for plotting
